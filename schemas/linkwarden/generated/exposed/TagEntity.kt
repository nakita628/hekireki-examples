package linkwarden.models

import org.jetbrains.exposed.v1.core.dao.id.EntityID
import org.jetbrains.exposed.v1.dao.Entity
import org.jetbrains.exposed.v1.dao.EntityBatchUpdate
import org.jetbrains.exposed.v1.dao.EntityClass
import java.time.Instant
import java.time.temporal.ChronoUnit

class TagEntity(
    id: EntityID<Int>,
) : Entity<Int>(id) {
    companion object : EntityClass<Int, TagEntity>(TagTable)

    var name by TagTable.name
    var links by LinkEntity via LinkToTagTable
    var owner by UserEntity referencedOn TagTable.ownerId
    var ownerId by TagTable.ownerId
    var archiveAsScreenshot by TagTable.archiveAsScreenshot
    var archiveAsMonolith by TagTable.archiveAsMonolith
    var archiveAsPDF by TagTable.archiveAsPDF
    var archiveAsReadable by TagTable.archiveAsReadable
    var archiveAsWaybackMachine by TagTable.archiveAsWaybackMachine
    var aiTag by TagTable.aiTag
    var aiGenerated by TagTable.aiGenerated
    var createdAt by TagTable.createdAt
    var updatedAt by TagTable.updatedAt

    override fun flush(batch: EntityBatchUpdate?): Boolean {
        if (writeValues.isNotEmpty()) {
            if (!isWritten(TagTable.updatedAt)) {
                updatedAt = Instant.now().truncatedTo(ChronoUnit.MILLIS)
            }
        }
        return super.flush(batch)
    }
}
