package langwatch.models

import org.jetbrains.exposed.v1.core.dao.id.EntityID
import org.jetbrains.exposed.v1.dao.Entity
import org.jetbrains.exposed.v1.dao.EntityBatchUpdate
import org.jetbrains.exposed.v1.dao.EntityClass
import java.time.Instant
import java.time.temporal.ChronoUnit

class TopicEntity(
    id: EntityID<String>,
) : Entity<String>(id) {
    companion object : EntityClass<String, TopicEntity>(TopicTable)

    var projectId by TopicTable.projectId
    var name by TopicTable.name
    var parentId by TopicTable.parentId
    var embeddingsModel by TopicTable.embeddingsModel
    var centroid by TopicTable.centroid
    var p95Distance by TopicTable.p95Distance
    var automaticallyGenerated by TopicTable.automaticallyGenerated
    var lastEventId by TopicTable.lastEventId
    var createdAt by TopicTable.createdAt
    var updatedAt by TopicTable.updatedAt

    override fun flush(batch: EntityBatchUpdate?): Boolean {
        if (writeValues.isNotEmpty()) {
            if (!isWritten(TopicTable.updatedAt)) {
                updatedAt = Instant.now().truncatedTo(ChronoUnit.MILLIS)
            }
        }
        return super.flush(batch)
    }
}
